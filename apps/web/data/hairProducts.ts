function lengths(min: number, max: number, step = 2, deltaPerStep = 15000): VariantGroup {
  const values = [];
  for (let n = min, i = 0; n <= max; n += step, i++)
    values.push({ label: `${n} inches`, priceDelta: i * deltaPerStep });
  return { key: 'length', name: 'Length', values };
}

function lengthNums(min: number, max: number, step = 2): number[] {
  const out: number[] = [];
  for (let n = min; n <= max; n += step) out.push(n);
  return out;
}

